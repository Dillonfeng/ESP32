#!/usr/bin/env python3
"""
gen_almnum.py - Generate antialiased 8-bit masks (62 x 112) for the numerals 0..9
used by the ALMANAC (黄历) popup's big day number.

Same font as the split-flap digits (Bahnschrift variable font) but BOLD
(weight axis 700) and in a larger box, so the day of month reads as a
prominent bold numeral ("大而突出, 粗体" request, 2026-09-25).

Mask convention (same as digits.h / dialnum.h): 0 = stroke, 255 = background.
Composited at draw time:  out = bg*m + fg*(255-m)  (per 565 channel).

Run:  python scripts/gen_almnum.py
Output: d:/ESP32-S3/include/almnum.h
"""
from PIL import Image, ImageDraw, ImageFont
import os

ALM_DW = 62
ALM_DH = 112
FONT_PX = 240
MARGIN = 2
BAHNSCHRIFT = r"C:\Windows\Fonts\bahnschrift.ttf"
BAHNS_WEIGHT = 700       # bold (variable font Weight axis 300..700)
BAHNS_WIDTH = 100        # normal width
FONT_CANDIDATES = [
    r"C:\Windows\Fonts\candaral.ttf",
    r"C:\Windows\Fonts\segoeuib.ttf",
    r"C:\Windows\Fonts\consolab.ttf",
    r"C:\Windows\Fonts\arialbd.ttf",
    r"C:\Windows\Fonts\arial.ttf",
]
OUT = r"d:/ESP32-S3/include/almnum.h"


def pick_font():
    if os.path.exists(BAHNSCHRIFT):
        return BAHNSCHRIFT, True
    for p in FONT_CANDIDATES:
        if os.path.exists(p):
            return p, False
    raise RuntimeError("No usable font found")


def common_scale(font):
    """ONE shared scale for 0..9 so every digit has the same pixel height."""
    d = ImageDraw.Draw(Image.new("L", (10, 10), 0))
    max_w = ALM_DW - MARGIN * 2
    max_h = ALM_DH - MARGIN * 2
    scale = max_h / d.textbbox((0, 0), "0", font=font)[3]
    for ch in "0123456789":
        b = d.textbbox((0, 0), ch, font=font)
        scale = min(scale, max_w / (b[2] - b[0]), max_h / (b[3] - b[1]))
    return scale


def render_mask(ch, scale, font):
    bbox = font.getbbox(ch)
    gw = bbox[2] - bbox[0]
    gh = bbox[3] - bbox[1]
    nw = max(1, int(round(gw * scale)))
    nh = max(1, int(round(gh * scale)))
    pad = 24
    big = Image.new("L", (gw + pad * 2, gh + pad * 2), 255)
    bd = ImageDraw.Draw(big)
    bd.text((pad - bbox[0], pad - bbox[1]), ch, font=font, fill=0)
    small = big.resize((nw, nh), Image.LANCZOS)
    canvas = Image.new("L", (ALM_DW, ALM_DH), 255)
    canvas.paste(small, ((ALM_DW - nw) // 2, (ALM_DH - nh) // 2))
    return canvas


def main():
    f, is_bahns = pick_font()
    print("Using font:", f, "(Bahnschrift w%d)" % BAHNS_WEIGHT if is_bahns else "(fallback)")
    font = ImageFont.truetype(f, FONT_PX)
    if is_bahns:
        try:
            font.set_variation_by_axes([BAHNS_WEIGHT, BAHNS_WIDTH])
        except Exception:
            pass
    scale = common_scale(font)
    print("shared scale:", round(scale, 5))

    lines = []
    lines.append("// AUTO-GENERATED by scripts/gen_almnum.py -- do not edit by hand")
    lines.append("// Antialiased 8-bit digit masks for the ALMANAC popup big day number.")
    lines.append("// %d x %d, Bahnschrift weight %d (bold). 0 = stroke, 255 = background." % (ALM_DW, ALM_DH, BAHNS_WEIGHT))
    lines.append("// Composite (per 565 channel): out = bg*m + fg*(255-m).")
    lines.append("#ifndef ALMNUM_H")
    lines.append("#define ALMNUM_H")
    lines.append("")
    lines.append("#include <Arduino.h>")
    lines.append("")
    lines.append("#define ALM_DW %d" % ALM_DW)
    lines.append("#define ALM_DH %d" % ALM_DH)
    for i in range(10):
        img = render_mask(str(i), scale, font)
        lines.append("const uint8_t AlmMask%d[%d] PROGMEM = {" % (i, ALM_DW * ALM_DH))
        row = []
        for y in range(ALM_DH):
            for x in range(ALM_DW):
                row.append(str(img.getpixel((x, y))))
                if len(row) == 16:
                    lines.append("  " + ", ".join(row) + ",")
                    row = []
        if row:
            lines.append("  " + ", ".join(row))
        lines.append("};")
        lines.append("")
    lines.append("const uint8_t *const AlmMasks[10] PROGMEM = {")
    lines.append("  AlmMask0, AlmMask1, AlmMask2, AlmMask3, AlmMask4,")
    lines.append("  AlmMask5, AlmMask6, AlmMask7, AlmMask8, AlmMask9")
    lines.append("};")
    lines.append("")
    lines.append("#endif // ALMNUM_H")
    lines.append("")
    with open(OUT, "w", newline="\r\n") as fh:
        fh.write("\n".join(lines))
    print("Wrote", OUT)


if __name__ == "__main__":
    main()
