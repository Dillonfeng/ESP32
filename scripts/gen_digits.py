#!/usr/bin/env python3
"""
gen_digits.py - Generate 16-bit 565 color digit sprites for the ESP32-S3 split-flap clock.

Each digit '0'..'9' is rendered with high-quality antialiasing (8x supersampling)
using a bold geometric font (Bahnschrift if present, else Arial Bold).
The sprite is a flat, vertically-centered glyph (no per-card scaling), so when
pasted with drawRGB() it looks as smooth as a normal FreeFont string -- unlike
FreeFont's internal integer scaling which jags at scale 3.

Output:
  d:/ESP32-S3/include/digits.h
    - DigitSprite[10] : uint16_t bitmap (56x120 RGB565, top-to-bottom rows)
    - DIGIT_W / DIGIT_H defines

The bitmap is stored in natural orientation. On the display (rot 1 -> MV only,
no MV2) a sprite that is vertically symmetric is unaffected; the digits are
centered so they read correctly.

Run:  python scripts/gen_digits.py
"""
from PIL import Image, ImageDraw, ImageFont
import os
import sys

DIGIT_W = 56
DIGIT_H = 120
SS = 8                      # supersampling factor
FONT_CANDIDATES = [
    r"C:\Windows\Fonts\bahnschrift.ttf",
    r"C:\Windows\Fonts\segoeui.ttf",
    r"C:\Windows\Fonts\arialbd.ttf",
    r"C:\Windows\Fonts\arial.ttf",
    r"C:\Windows\Fonts\verdanab.ttf",
]
OUT = r"d:/ESP32-S3/include/digits.h"

# Glyph target size (cap height / overall) in the 1x image, then we scale.
# We render a big glyph and crop to the glyph's own bounding box, then place
# it centered in the 56x120 card.
GLYPH_PX = 96               # point size used for the bold glyph


def pick_font():
    for p in FONT_CANDIDATES:
        if os.path.exists(p):
            return p
    # fallback: let PIL find any default ttf by name
    for n in ["Bahnschrift", "Arial", "Segoe UI", "DejaVuSans-Bold.ttf"]:
        try:
            ImageFont.truetype(n, 20)
            return n
        except Exception:
            pass
    raise RuntimeError("No usable font found")


def render_digit(ch):
    f = pick_font()
    font = ImageFont.truetype(f, GLYPH_PX)

    # Measure the exact glyph box
    dummy = Image.new("L", (10, 10), 0)
    d = ImageDraw.Draw(dummy)
    bbox = d.textbbox((0, 0), ch, font=font)
    gw = bbox[2] - bbox[0]
    gh = bbox[3] - bbox[1]

    # Scale glyph so it fits inside the card with vertical margin.
    max_w = DIGIT_W * SS - 8 * SS      # keep 8px side margin
    max_h = (DIGIT_H - 24) * SS        # keep 12px top/bottom margin

    scale = min(max_w / gw, max_h / gh)
    if scale > 1.0:
        scale = 1.0  # never upscale beyond designed size (avoids blurriness)
    # Actually we WANT it large & smooth: allow up to max box (font px is big).
    scale = min(max_w / gw, max_h / gh)

    new_w = int(round(gw * scale))
    new_h = int(round(gh * scale))

    # Render supersampled: draw glyph onto a big 'L' canvas, downscale with
    # LANCZOS to get smooth antialiasing, then convert to RGB565 with a
    # black-on-white (black digit) palette.
    big = Image.new("L", (new_w + SS, new_h + SS), 255)   # 255 = white bg
    bd = ImageDraw.Draw(big)
    # draw centered in the SS pad
    ox = (new_w - gw) / 2 - bbox[0]
    oy = (new_h - gh) / 2 - bbox[1]
    bd.text((ox, oy), ch, font=font, fill=0)  # black glyph

    # Downscale by SS to final size with smooth edges
    small = big.resize((new_w // SS + 1, new_h // SS + 1), Image.LANCZOS)

    # Crop any +1 pixel artifact
    small = small.crop((0, 0, new_w // SS, new_h // SS))

    # Build a 56x120 canvas (white), paste the digit centered
    canvas = Image.new("L", (DIGIT_W, DIGIT_H), 255)
    px = (DIGIT_W - small.width) // 2
    py = (DIGIT_H - small.height) // 2
    canvas.paste(small, (px, py))

    return canvas


def to_rgb565_array(img):
    """Return (values:list[int], hexstr) of RGB565 top-to-bottom pixels."""
    vals = []
    for y in range(img.height):
        for x in range(img.width):
            g = img.getpixel((x, y))          # 0..255 luminance (0=black digit,255=white)
            # white card face -> keep white; digit -> near black.
            # Map to RGB565 with slight blue tint to match the reference.
            r = g
            gg = g
            b = g
            r5 = (r >> 3)
            g6 = (gg >> 2)
            b5 = (b >> 3)
            c565 = (r5 << 11) | (g6 << 5) | b5
            vals.append(c565)
    return vals


def main():
    f = pick_font()
    print("Using font:", f)
    lines = []
    lines.append("// AUTO-GENERATED by scripts/gen_digits.py -- do not edit by hand")
    lines.append("// Bold antialiased digit sprites (RGB565) for the split-flap clock.")
    lines.append("#ifndef DIGITS_H")
    lines.append("#define DIGITS_H")
    lines.append("")
    lines.append("#define DIGIT_W %d" % DIGIT_W)
    lines.append("#define DIGIT_H %d" % DIGIT_H)
    lines.append("")
    lines.append("#include <Arduino.h>")
    lines.append("")
    lines.append("// DigitSprite[i] holds the 56x120 RGB565 bitmap for digit '0'+i.")
    lines.append("// Draw with:  tft.drawRGB(x, y, DIGIT_W, DIGIT_H, DigitSprite[i]);")
    for i in range(10):
        img = render_digit(chr(ord('0') + i))
        vals = to_rgb565_array(img)
        lines.append("const uint16_t DigitSprite%d[] PROGMEM = {" % i)
        # 12 per line
        row = []
        for v in vals:
            row.append("0x%04X" % v)
            if len(row) == 12:
                lines.append("  " + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("  " + ", ".join(row))
        lines.append("};")
        lines.append("")
    lines.append("// Total bytes per sprite")
    lines.append("#define DIGIT_BYTES (DIGIT_W * DIGIT_H * 2)")
    lines.append("")
    lines.append("#endif // DIGITS_H")
    lines.append("")

    with open(OUT, "w", newline="\r\n") as fh:
        fh.write("\n".join(lines))
    print("Wrote", OUT)
    print("Sprite size: %dx%d = %d px = %d bytes each, 10 sprites" % (DIGIT_W, DIGIT_H, DIGIT_W * DIGIT_H, DIGIT_W * DIGIT_H * 2))


if __name__ == "__main__":
    main()
