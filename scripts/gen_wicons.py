#!/usr/bin/env python3
"""gen_wicons.py - Generate clean 24x24 weather-icon pixel bitmaps.
Outputs:
  - include/wicons.h       (C: const uint8_t W_ICON[8][24][24])
  - preview/wicons.py      (Python: W_ICONS dict + W_ICON_PAL)
Both are produced from the SAME geometry so hardware and preview are
pixel-identical by construction (lockstep).

Palette index per pixel (0=transparent):
  1=sun 2=cloud 3=cloudshadow 4=rain 5=snow 6=warn 7=mist
"""
import math, os

S = 24
C = 11.5  # grid center (0-indexed, symmetric)

def new():
    return [[0]*S for _ in range(S)]

def circle(g, cx, cy, r, val):
    rr = r*r
    for y in range(S):
        for x in range(S):
            if (x-cx)*(x-cx) + (y-cy)*(y-cy) <= rr:
                g[y][x] = val

def ring(g, cx, cy, r0, r1, val):
    for y in range(S):
        for x in range(S):
            d = (x-cx)*(x-cx) + (y-cy)*(y-cy)
            if r0*r0 <= d <= r1*r1:
                g[y][x] = val

def ellipse(g, cx, cy, rx, ry, val):
    for y in range(S):
        for x in range(S):
            if ((x-cx)/rx)**2 + ((y-cy)/ry)**2 <= 1.0:
                g[y][x] = val

def hseg(g, y, x0, x1, val):
    for x in range(max(0, x0), min(S-1, x1) + 1):
        g[y][x] = val

def sun_rays(g, cx, cy, r0, r1, val, thick=1):
    for a in range(8):
        th = a*math.pi/4.0
        for t in range(int(r0), int(r1)+1):
            bx = int(round(cx + t*math.cos(th)))
            by = int(round(cy + t*math.sin(th)))
            for dy in range(-thick+1, thick):
                for dx in range(-thick+1, thick):
                    x, y = bx+dx, by+dy
                    if 0 <= x < S and 0 <= y < S:
                        g[y][x] = val

def cloud(g, cx, cy, rx, ry, val):
    """Classic puffy cloud: bottom ellipse + two top bumps."""
    ellipse(g, cx, cy, rx, ry, val)
    circle(g, cx - rx*0.55, cy - ry*0.35, ry*0.85, val)
    circle(g, cx + rx*0.15, cy - ry*0.55, ry*0.95, val)
    circle(g, cx + rx*0.6, cy - ry*0.15, ry*0.7, val)

def drop(g, x, y0, y1, val):
    for y in range(y0, y1+1):
        if 0 <= y < S:
            g[y][x] = val

def stroke(g, pts, val, w=2):
    """Bresenham polyline, w px wide (used for the lightning bolt)."""
    hw = (w - 1) // 2
    for i in range(len(pts) - 1):
        x0, y0 = pts[i]; x1, y1 = pts[i + 1]
        dx, dy = abs(x1 - x0), abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx - dy
        while True:
            for ox in range(-hw, hw + 1):
                for oy in range(-hw, hw + 1):
                    xx, yy = x0 + ox, y0 + oy
                    if 0 <= xx < S and 0 <= yy < S:
                        g[yy][xx] = val
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 > -dx:
                err -= dy; x0 += sx
            if e2 < dy:
                err += dx; y0 += sy

def flake(g, x, y, val):
    """clean snowflake: vertical + horizontal + 2 diagonals, radius 2."""
    for (dx, dy) in ((0,0),(1,0),(-1,0),(0,1),(0,-1),(2,0),(-2,0),(0,2),(0,-2),
                     (1,1),(1,-1),(-1,1),(-1,-1)):
        xx, yy = x+dx, y+dy
        if 0 <= xx < S and 0 <= yy < S:
            g[yy][xx] = val

icons = {}

# 0: clear day - sun
g = new()
circle(g, C, C, 6, 1)
sun_rays(g, C, C, 8, 10, 1, 1)
icons[0] = g

# 1: partly cloudy - small sun (upper-left) + cloud (lower-right)
g = new()
circle(g, 8, 8, 4, 1)
sun_rays(g, 8, 8, 5.5, 7, 1, 1)
cloud(g, 14, 15, 7, 5, 2)
icons[1] = g

# 2: overcast - big cloud
g = new()
cloud(g, C, 14, 8, 5, 2)
icons[2] = g

# 3: fog - cloud + 3 mist lines
g = new()
cloud(g, C, 10, 7, 4, 2)
hseg(g, 16, 6, 18, 7)
hseg(g, 18, 4, 16, 7)
hseg(g, 20, 8, 20, 7)
icons[3] = g

# 4: rain - cloud + 3 drops
g = new()
cloud(g, C, 11, 8, 5, 2)
for x in (8, 12, 16):
    drop(g, x, 17, 20, 4)
icons[4] = g

# 5: drizzle - cloud + 2 short drops
g = new()
cloud(g, C, 11, 8, 5, 2)
for x in (9, 15):
    drop(g, x, 17, 19, 4)
icons[5] = g

# 6: snow - cloud (higher) + 3 spaced flakes
g = new()
cloud(g, C, 9, 8, 4, 2)
for (x, y) in ((6, 17), (12, 19), (18, 17)):
    flake(g, x, y, 5)
icons[6] = g

# 7: thunderstorm - cloud + clean zigzag bolt
g = new()
cloud(g, C, 10, 8, 4, 2)
stroke(g, [(13, 15), (9, 19), (13, 19), (10, 22)], 6, w=2)
icons[7] = g

# ---- emit ----
def emit():
    # C header
    h = ["// Auto-generated by scripts/gen_wicons.py -- DO NOT EDIT BY HAND.",
         "// 24x24 weather icon bitmaps (palette index per pixel; 0=transparent).",
         "// Palette: 1=sun 2=cloud 3=cloudshadow 4=rain 5=snow 6=warn 7=mist.",
         "#pragma once", "#include <stdint.h>", ""]
    for t in range(8):
        g = icons[t]
        vals = ",".join(str(g[y][x]) for y in range(S) for x in range(S))
        h.append("static const uint8_t W_ICON%d[%d] = {" % (t, S*S))
        for y in range(S):
            h.append("  " + ",".join(str(g[y][x]) for x in range(S)) + ",")
        h.append("};")
    h.append("static const uint8_t* const W_ICON[8] = " +
             ",".join("W_ICON%d" % t for t in range(8)) + ";")
    open(r"D:\ESP32-S3\include\wicons.h", "w", encoding="utf-8").write("\n".join(h) + "\n")

    # Python module
    p = ["# Auto-generated by scripts/gen_wicons.py -- DO NOT EDIT BY HAND.",
         "W_ICON_SIZE = 24",
         "# palette index -> 565 (same as main.cpp wIconPal)",
         "W_ICON_PAL565 = {0: None, 1: 0xFFE0, 2: 0xFFFF, 3: 0xC63C, 4: 0x4DDF, 5: 0x7DFF, 6: 0xFD20, 7: 0xBDF7}",
         "W_ICONS = {"]
    for t in range(8):
        g = icons[t]
        p.append("  %d: [" % t)
        for y in range(S):
            p.append("    [" + ",".join(str(g[y][x]) for x in range(S)) + "],")
        p.append("  ],")
    p.append("}")
    open(r"D:\ESP32-S3\preview\wicons.py", "w", encoding="utf-8").write("\n".join(p) + "\n")

    # render a preview PNG for visual check (independent of make_preview)
    from PIL import Image
    def c565(h):
        return (((h >> 11) * 255 // 31,
                 ((h >> 5) & 0x3F) * 255 // 63,
                 (h & 0x1F) * 255 // 31))
    pal = {0: None, 1: c565(0xFFE0), 2: c565(0xFFFF), 3: c565(0xC63C),
           4: c565(0x4DDF), 5: c565(0x7DFF), 6: c565(0xFD20), 7: c565(0xBDF7)}
    cell = 96  # 24x4 scale for visibility
    img = Image.new("RGB", (8*cell, cell), (30, 30, 34))
    for t in range(8):
        g = icons[t]
        small = Image.new("RGB", (S, S), (30, 30, 34))
        for y in range(S):
            for x in range(S):
                c = pal[g[y][x]]
                if c:
                    small.putpixel((x, y), c)
        big = small.resize((cell, cell), Image.NEAREST)
        img.paste(big, (t*cell, 0))
    img.save(r"D:\ESP32-S3\preview\wicons_preview.png")
    print("wrote include/wicons.h, preview/wicons.py, preview/wicons_preview.png")

if __name__ == "__main__":
    os.chdir(r"D:\ESP32-S3\preview")
    emit()
