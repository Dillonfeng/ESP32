"""
Generate cassette deck assets for ESP32 recorder UI.
Outputs:
  - data/deck_face.bin   : 480x320 RGB565 background (LittleFS)
  - include/deck_reels.h : left/right reel hub C arrays (30x30 RGB565, circular transparency)
"""
from PIL import Image
import struct, os

SRC = r"d:\ESP32-S3\recorder_ui\assets\deck_face.png"
OUT_BIN = r"d:\ESP32-S3\data\deck_face.bin"
OUT_H = r"d:\ESP32-S3\include\deck_reels.h"

# Reel centers in logical 480x320 coords (from HTML REELS)
REEL_L = (144.3, 93.5, 15.0)
REEL_R = (246.3, 93.6, 15.0)

def rgb888_to_565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

def make_565_buf(img):
    w, h = img.size
    rgb = img.convert("RGB")
    buf = bytearray(w * h * 2)
    px = rgb.load()
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            v = rgb888_to_565(r, g, b)
            o = (y * w + x) * 2
            buf[o] = v & 0xFF
            buf[o + 1] = (v >> 8) & 0xFF
    return bytes(buf)

def main():
    src = Image.open(SRC)
    print("source:", src.size, src.mode)

    # --- 1. Background: 960x640 -> 480x320 RGB565 ---
    bg = src.resize((480, 320), Image.LANCZOS)
    bg_bin = make_565_buf(bg)
    with open(OUT_BIN, "wb") as f:
        f.write(bg_bin)
    print(f"deck_face.bin: {len(bg_bin)} bytes (480x320 RGB565)")

    # --- 2. Reel hubs: extract from source at 2x scale, resize to 30x30, circular mask ---
    # transparent color = magenta 0xF81F (unlikely in reel imagery)
    TRANSP = 0xF81F
    reels = {}
    for name, (cx, cy, r) in [("L", REEL_L), ("R", REEL_R)]:
        # source (960x640) coords = logical * 2
        sx, sy, sr = cx * 2, cy * 2, r * 2
        # extract a square slightly larger than the circle for rotation headroom
        box = (int(sx - sr), int(sy - sr), int(sx + sr), int(sy + sr))
        crop = src.crop(box).resize((30, 30), Image.LANCZOS).convert("RGB")
        w, h = crop.size
        px = crop.load()
        cr2 = (w / 2.0) ** 2
        arr = []
        for y in range(h):
            for x in range(w):
                dx = x + 0.5 - w / 2.0
                dy = y + 0.5 - h / 2.0
                if dx * dx + dy * dy <= cr2:
                    r_, g_, b_ = px[x, y]
                    arr.append(rgb888_to_565(r_, g_, b_))
                else:
                    arr.append(TRANSP)
        reels[name] = arr
        print(f"reel {name}: {w}x{h}, {len(arr)} pixels")

    # --- 3. Write C header ---
    with open(OUT_H, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by scripts/gen_deck_assets.py -- DO NOT EDIT BY HAND.\n")
        f.write("// Cassette deck reel hubs (30x30 RGB565, magenta 0xF81F = transparent).\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define DECK_REEL_W 30\n#define DECK_REEL_H 30\n")
        f.write("#define DECK_REEL_TRANSP 0xF81F\n\n")
        for name in ("L", "R"):
            f.write(f"static const uint16_t DECK_REEL_{name}[DECK_REEL_W*DECK_REEL_H] = {{\n")
            arr = reels[name]
            for i in range(0, len(arr), 12):
                row = ", ".join(f"0x{v:04X}" for v in arr[i:i+12])
                f.write(f"  {row},\n")
            f.write("};\n\n")
    print(f"deck_reels.h written")

if __name__ == "__main__":
    main()
