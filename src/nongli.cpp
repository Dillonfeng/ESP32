/**
 * 月相计算, 返回 0..1 (0=新月, 0.5=满月)。
 * 基于儒略日(JD)与朔望月周期 29.530588853 天, 以 2000-01-06 18:14 UTC 新月为参考。
 * 取当日 12:00 (本地) 计算, 精度约 ±1 天, 足够显示月相名与图标。
 */
double nl_moon_phase(int year, int month, int day) {
    int yy = year, mm = month;
    if (mm <= 2) { yy -= 1; mm += 12; }
    int A = yy / 100;
    int B = 2 - A + A / 4;
    // 标准儒略日 (Meeus): 前两项取整, 与 make_preview.py 完全一致
    double jd = floor(365.25 * (yy + 4716)) + floor(30.6001 * (mm + 1)) + day + B - 1524.5 + 12.0 / 24.0;
    double age = jd - 2451550.1;
    age = age - floor(age / 29.530588853) * 29.530588853;  // 取模 (处理负值)
    return age / 29.530588853;
}

