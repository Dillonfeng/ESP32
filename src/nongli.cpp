// ===== 公历辅助 =====
static int g_leap(int y) { return (y % 4 == 0 && y % 100 != 0) || (y % 400 == 0); }

static int g_days_in_month(int y, int m) {
    static const int dm[12] = {31,28,31,30,31,30,31,31,30,31,30,31};
    if (m == 2 && g_leap(y)) return 29;
    return dm[m - 1];
}

// 距 1900-01-01 的天数 (0 = 1900-01-01)
static int dn_days(int y, int m, int d) {
    int days = 0;
    for (int yy = 1900; yy < y; yy++) days += g_leap(yy) ? 366 : 365;
    for (int mm = 1; mm < m; mm++)  days += g_days_in_month(y, mm);
    days += d - 1;
    return days;
}

// ===== 农历表辅助 =====
// 某农历年的总天数 (含闰月)
static int lunar_year_days(int y) {
    int v = lunarInfo[y - 1900];
    int t = 0;
    for (int m = 1; m <= 12; m++) t += (v & (1 << (15 - (m - 1)))) ? 30 : 29;
    if (v & 0x0F) t += (v & (1 << 16)) ? 30 : 29;
    return t;
}

static int lunar_month_days(int y, int m) {
    return (lunarInfo[y - 1900] & (1 << (15 - (m - 1)))) ? 30 : 29;
}

static int lunar_leap_days(int y) {
    return (lunarInfo[y - 1900] & (1 << 16)) ? 30 : 29;
}

/**
 * 根据公历年/月计算该月每天的农历, 写入 result[0..daysInMonth-1]。
 * 编码约定 (与 main.cpp 解码一致):
 *   普通月 M, 日 D   -> M*100 + D
 *   闰月   M, 日 D   -> (100+M)*100 + D   (正数, 解码时 lm>100 判定闰月)
 */
void nl_month_days(int year, int month, int* result){
    if (year < 1900 || year > 2099 || month < 1 || month > 12) {
        return;
    }
    int dim = g_days_in_month(year, month);
    for (int d = 1; d <= dim; d++) {
        // 以 1900-01-31(农历1900正月初一) 为起点, 偏移 -30 得到 0-based 积日
        int days = dn_days(year, month, d) - 30;

        // 定位农历年
        int ly = 1900;
        while (ly < 2100) {
            int L = lunar_year_days(ly);
            if (days < L) break;
            days -= L;
            ly++;
        }

        // 定位农历月 (含闰月)
        int leap = lunarInfo[ly - 1900] & 0x0F;   // 闰月编号, 0 = 无
        int m = 1;
        bool isLeap = false;
        for (;;) {
            int dim2 = isLeap ? lunar_leap_days(ly) : lunar_month_days(ly, m);
            if (days < dim2) break;
            days -= dim2;
            if (!isLeap && m == leap) { isLeap = true; continue; } // 月M后接闰M
            isLeap = false;
            m++;
        }

        int lmonth = isLeap ? (100 + m) : m;
        result[d - 1] = lmonth * 100 + (days + 1);
    }
}

