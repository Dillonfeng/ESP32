/**
 * 返回当前节气与下一节气 (天文表查表, 精确到日, 含跨年)。
 * 输入: 公历年/月/日
 * 输出 (指针可为 NULL 表示不取):
 *   curIdx   - 当前节气编号 0..23 (对应 nl_jq_text)
 *   curDays  - 距当前节气已过天数
 *   nextIdx  - 下一节气编号 0..23
 *   nextDays - 距下一节气剩余天数
 * 返回 1 表示成功, 0 表示失败。
 */
int nl_jq_info(int year, int month, int day,
               int* curIdx, int* curDays, int* nextIdx, int* nextDays) {
    if (year < 1900 || year > 2100) return 0;
    int today = dn_days(year, month, day);  // 绝对积日 (自 1900-01-01)
    // 当前节气: 最近一个不晚于 today 的节气 (前一年 + 当年, 处理跨年)
    int bestIdx = -1, bestDay = -1 << 30;
    for (int yy = year - 1; yy <= year; yy++) {
        if (yy < 1900 || yy > 2099) continue;
        for (int i = 0; i < 24; i++) {
            int ad = dn_days(yy, 1, 1) + (JQ_DOY[yy - 1900][i] - 1);
            if (ad <= today && ad > bestDay) { bestDay = ad; bestIdx = i; }
        }
    }
    // 下一节气: 最近一个晚于 today 的节气 (当年 + 后一年)
    int nxtIdx = -1, nxtDay = 1 << 30;
    for (int yy = year; yy <= year + 1; yy++) {
        if (yy < 1900 || yy > 2099) continue;
        for (int i = 0; i < 24; i++) {
            int ad = dn_days(yy, 1, 1) + (JQ_DOY[yy - 1900][i] - 1);
            if (ad > today && ad < nxtDay) { nxtDay = ad; nxtIdx = i; }
        }
    }
    if (bestIdx < 0 || nxtIdx < 0) return 0;
    if (curIdx)   *curIdx   = bestIdx;
    if (curDays)  *curDays  = today - bestDay;
    if (nextIdx)  *nextIdx  = nxtIdx;
    if (nextDays) *nextDays = nxtDay - today;
    return 1;
}

