def easter(year):
    """格里高利历复活节 (Meeus/Jones/Butcher 算法). 返回 datetime.date."""
    import datetime
    a = year % 19
    b = year // 100
    c = year % 100
    d = b // 4
    e = b % 4
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i = c // 4
    k = c % 4
    l = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * l) // 451
    month = (h + l - 7 * m + 114) // 31
    day = ((h + l - 7 * m + 114) % 31) + 1
    return datetime.date(year, month, day)


def thanksgiving(year):
    """美国感恩节 = 11 月第 4 个星期四. 返回 datetime.date."""
    import datetime
    first = datetime.date(year, 11, 1)
    off = (3 - first.weekday()) % 7   # 11/1 到第 1 个星期四
    return first + datetime.timedelta(days=off + 21)


def festival_of(y, m, d, ly, lm, ldn, isleap):
    """返回当天节日名 (无则 ''). ly/lm/ldn 为农历(非闰, 闰月不视为节日)。
    与 nongli.cpp nl_festival() 完全一致。"""
    import datetime
    # 1) 农历固定节日 (仅非闰月)
    if not isleap:
        name = LUNAR_FESTIVALS.get((lm, ldn))
        if name:
            return name
    # 2) 公历固定节日
    name = SOLAR_FESTIVALS.get((m, d))
    if name:
        return name
    # 3) 浮动节日: 感恩节 / 复活节
    if d == thanksgiving(y).day and m == 11:
        return '感恩节'
    if datetime.date(y, m, d) == easter(y):
        return '复活节'
    return ''
